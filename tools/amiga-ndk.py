#!/usr/bin/env python3
"""Install the AmigaOS headers and OS call stubs into the m68k-amigaos sysroot.

The headers and library descriptions come from Hyperion's Native Developer
Kit for AmigaOS 3.2 (NDK 3.2), which is free to download from Aminet but
may not be passed on with this SDK. This script downloads it (or takes a
copy you have), checks it, and installs:

  include/        the NDK's C headers, with proto/ headers for clang
  lib/libamiga.a  a stub for each public function of every OS library,
                  which loads the arguments into the registers the library
                  expects and calls it through its base in a6, and
                  the amiga.lib helpers of this SDK (os/alib)

    amiga-ndk.py [--sysroot DIR] [--archive NDK3.2.lha] [--bin DIR]

By default the sysroot is m68k-amigaos and the tools are in bin, next to
the share directory this script is in.
"""
import argparse
import concurrent.futures
import hashlib
import os
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fd2stub  # noqa: E402
import lha  # noqa: E402

NDK_NAME = "NDK 3.2 Release 4"
NDK_SHA256 = "96cabd4ad683dced632e147bf86dee0f50dcb1254386216c25c362916a6409bb"
NDK_URLS = [
    "https://aminet.net/dev/misc/NDK3.2.lha",
    "https://de4.aminet.net/dev/misc/NDK3.2.lha",
    "https://ftp.fau.de/aminet/dev/misc/NDK3.2.lha",
]


def download():
    errors = []
    for url in NDK_URLS:
        try:
            print("downloading", url)
            with urllib.request.urlopen(url, timeout=60) as r:
                data = r.read()
            if hashlib.sha256(data).hexdigest() == NDK_SHA256:
                return data
            errors.append("%s: not the expected file" % url)
        except OSError as e:
            errors.append("%s: %s" % (url, e))
    sys.exit("could not download the NDK:\n  " + "\n  ".join(errors))


def find_tool(bindir, name):
    exe = name + (".exe" if os.name == "nt" else "")
    if bindir:
        path = os.path.join(bindir, exe)
        if os.path.exists(path):
            return path
    path = shutil.which(name)
    if not path:
        sys.exit("%s not found; pass --bin" % name)
    return path


# clang has no register parameters (gcc's "p __asm(r)"), and no __fast
# or __interrupt. With these, the NDK headers' function pointer types with
# register arguments are plain C ones: calling one needs inline assembly.
CLANG_COMPILER_SPECIFIC = b"""
/* Added by amiga-ndk.py for clang. */
#if defined(__clang__)
#ifndef __REG__
#define __REG__(r, p) p
#endif
#ifndef __ASM__
#define __ASM__
#endif
#ifndef __INTERRUPT__
#define __INTERRUPT__
#endif
#ifndef __FAST__
#define __FAST__
#endif
#endif
"""


def patch_header(rel, body):
    if rel == "clib/compiler-specific.h":
        marker = b"#define\tCOMPILER_SPECIFIC_H\n"
        if marker not in body:
            marker = b"#define COMPILER_SPECIFIC_H\n"
        if marker in body:
            body = body.replace(marker, marker + CLANG_COMPILER_SPECIFIC, 1)
    return body


def proto_header(lib, base, btype):
    guard = "PROTO_%s_H" % lib.upper()
    return """\
#ifndef {guard}
#define {guard}
/* Generated by amiga-ndk.py: the C prototypes of {lib}, which link to
   the stubs in libamiga.a, and its library base. */
#include <clib/{lib}_protos.h>
#ifndef __NOLIBBASE__
extern {btype} *{base};
#endif
#endif
""".format(guard=guard, lib=lib, base=base, btype=btype)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(os.path.dirname(here))
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--sysroot", default=os.path.join(root, "m68k-amigaos"))
    ap.add_argument("--archive", help="NDK3.2.lha you already have")
    ap.add_argument("--bin", default=os.path.join(root, "bin"),
                    help="directory with clang and llvm-ar")
    ap.add_argument("--no-stubs", action="store_true",
                    help="install the headers only, not libamiga.a")
    args = ap.parse_args()

    if not args.no_stubs:
        clang = find_tool(args.bin, "clang")
        llvm_ar = find_tool(args.bin, "llvm-ar")
    if args.archive:
        with open(args.archive, "rb") as f:
            data = f.read()
        if hashlib.sha256(data).hexdigest() != NDK_SHA256:
            print("warning: %s is not %s from Aminet; installing it anyway"
                  % (args.archive, NDK_NAME))
    else:
        data = download()

    inc = os.path.join(args.sysroot, "include")
    libdir = os.path.join(args.sysroot, "lib")
    os.makedirs(inc, exist_ok=True)
    os.makedirs(libdir, exist_ok=True)

    fds = {}
    ndk_protos = {}
    count = 0
    for name, body in lha.extract(data, lambda n: n.startswith(("Include_H/", "FD/"))):
        if name.startswith("FD/"):
            if name.endswith("_lib.fd"):
                fds[os.path.basename(name)] = body
            continue
        rel = name[len("Include_H/"):]
        # inline/ is gcc's MIT-syntax assembly, which clang can't read, and
        # proto/ includes it; proto/ is generated below instead.
        if rel.startswith(("inline/", "proto/")) or rel.endswith(".info"):
            if rel.startswith("proto/"):
                ndk_protos[os.path.basename(rel)] = body.decode("latin-1")
            continue
        dest = os.path.join(inc, *rel.split("/"))
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with open(dest, "wb") as f:
            f.write(patch_header(rel, body))
        count += 1
    print("installed %d headers in %s" % (count, inc))

    work = tempfile.mkdtemp(prefix="amiga-ndk-")
    try:
        stubdir = os.path.join(work, "stubs")
        os.makedirs(stubdir)
        fdpaths = []
        for fdname, body in sorted(fds.items()):
            path = os.path.join(work, fdname)
            with open(path, "wb") as f:
                f.write(body)
            fdpaths.append(path)

        protodir = os.path.join(inc, "proto")
        os.makedirs(protodir, exist_ok=True)
        nprotos = 0
        for path in fdpaths:
            lib = os.path.basename(path)[:-len("_lib.fd")]
            base, _ = fd2stub.parse_fd(path)
            if not base or not os.path.exists(
                    os.path.join(inc, "clib", lib + "_protos.h")):
                continue
            btype = "struct Library"
            m = re.search(r"extern\s+(struct\s+\w+)\s*\*\s*%s\s*;" % base,
                          ndk_protos.get(lib + ".h", ""))
            if m:
                btype = m.group(1)
            with open(os.path.join(protodir, lib + ".h"), "w") as f:
                f.write(proto_header(lib, base, btype))
            nprotos += 1
        print("generated %d proto headers" % nprotos)
        if args.no_stubs:
            return

        sys.argv = ["fd2stub", stubdir] + fdpaths
        fd2stub.main()
        sources = sorted(os.listdir(stubdir))

        def assemble(src):
            obj = os.path.join(stubdir, src[:-2] + ".o")
            subprocess.run([clang, "--target=m68k-amigaos", "-c",
                            os.path.join(stubdir, src), "-o", obj], check=True)
            return obj

        # The amiga.lib helpers (HookEntry, CreatePort, DoMethod, ...): next
        # to this script in the package, in os/alib in the source tree.
        alib = next((d for d in (os.path.join(here, "alib"),
                                 os.path.join(os.path.dirname(here), "os", "alib"))
                     if os.path.isdir(d)), None)
        rdir = subprocess.run([clang, "-print-resource-dir"], capture_output=True,
                              text=True, check=True).stdout.strip()

        def compile_alib(src):
            obj = os.path.join(stubdir, "alib-" + os.path.basename(src) + ".o")
            subprocess.run([clang, "--target=m68k-amigaos", "-Os", "-ffunction-sections",
                            "-nostdinc", "-isystem", inc,
                            "-isystem", os.path.join(rdir, "include"),
                            "-c", src, "-o", obj], check=True)
            return obj

        alib_srcs = sorted(os.path.join(alib, f) for f in os.listdir(alib)
                           if f.endswith((".c", ".S"))) if alib else []
        with concurrent.futures.ThreadPoolExecutor(os.cpu_count() or 4) as pool:
            objs = list(pool.map(assemble, sources))
            objs += list(pool.map(compile_alib, alib_srcs))
        lib = os.path.join(libdir, "libamiga.a")
        if os.path.exists(lib):
            os.remove(lib)
        # Write the member list to a response file: Windows command lines
        # are too short for a thousand names.
        rsp = os.path.join(work, "objs.rsp")
        with open(rsp, "w") as f:
            f.write("\n".join('"%s"' % o.replace("\\", "/") for o in objs))
        subprocess.run([llvm_ar, "rcs", lib, "@" + rsp], check=True)
        print("wrote %s (%d stubs, %d amiga.lib helpers)" % (lib, len(objs) - len(alib_srcs), len(alib_srcs)))
        with open(os.path.join(libdir, "amiga-ndk.txt"), "w") as f:
            f.write("%s, installed by amiga-ndk.py\n" % NDK_NAME)
    finally:
        shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    main()
